/**
 * Writes src/lib/label-chars.ts: the letters and numbers the label font can
 * print. Run `npm run label-chars` again whenever the font changes; a unit
 * test fails until the two match.
 */
import fontkit from '@pdf-lib/fontkit';
import { readFileSync, writeFileSync } from 'node:fs';

export const FONT = 'public/fonts/DejaVuSansMono-Bold.ttf';
const OUT = 'src/lib/label-chars.ts';

// pdf-lib draws glyphs one by one from left to right, so right-to-left scripts
// would come out back to front and without their joined letter forms
const RIGHT_TO_LEFT = /[\p{Script=Arabic}\p{Script=Hebrew}\p{Script=Syriac}\p{Script=Thaana}\p{Script=Nko}\p{Script=Adlam}]/u;

export function labelCharRanges(fontBytes: Uint8Array): [number, number][] {
  const font = fontkit.create(fontBytes);
  const points = font.characterSet
    .filter((cp) => {
      const ch = String.fromCodePoint(cp);
      return /[\p{L}\p{N}]/u.test(ch) && !RIGHT_TO_LEFT.test(ch) && font.hasGlyphForCodePoint(cp);
    })
    .sort((a, b) => a - b);
  const ranges: [number, number][] = [];
  for (const cp of points) {
    const last = ranges[ranges.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return ranges;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const ranges = labelCharRanges(readFileSync(FONT));
  const hex = (n: number) => `0x${n.toString(16)}`;
  const rows = ranges.map(([a, b]) => `[${hex(a)}, ${hex(b)}]`);
  const lines: string[] = [];
  for (let i = 0; i < rows.length; i += 8) lines.push(`  ${rows.slice(i, i + 8).join(', ')},`);
  writeFileSync(OUT, `// Generated by \`npm run label-chars\` from ${FONT}. Do not edit.

/** Letters and numbers the label font can print, as [first, last] code point ranges. */
export const LABEL_CHAR_RANGES: readonly [number, number][] = [
${lines.join('\n')}
];
`);
  console.log(`${OUT}: ${ranges.length} ranges`);
}
